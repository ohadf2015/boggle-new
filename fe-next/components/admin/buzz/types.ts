/**
 * Shared types for Daily Buzz Admin components
 */

export type RegenerableField = 'prompt' | 'answer' | 'hint' | 'options' | 'image' | 'all';

export interface BuzzChallengeAdmin {
  type: string;
  trend_topic: string;
  prompt: string;
  answer: string;
  hint?: string;
  difficulty: string;
  trending_context?: string;
  options?: string[];
}

export interface TrendingTopicAdmin {
  query: string;
  search_volume?: number;
}

export interface SocialPlatformContent {
  text: string;
  hashtags: string[];
}

export interface SocialContent {
  x: SocialPlatformContent;
  instagram: SocialPlatformContent;
  tiktok: SocialPlatformContent;
}

export interface DailyBuzzDataAdmin {
  puzzle_date: string;
  language: string;
  trending_summary: string;
  challenges: BuzzChallengeAdmin[];
  trending_topics: TrendingTopicAdmin[];
  // Image fields (nullable - can be removed by admin)
  image_url?: string | null;
  image_prompt?: string | null;
  image_category?: string | null;
  image_alt_text?: string | null;
  // Social media content (nullable - generated by AI)
  social_content?: SocialContent | null;
}

export interface PromptExample {
  id: string;
  challengeType: string;
  originalPrompt: string;
  originalAnswer: string;
  feedback: string;
  improvedPrompt?: string;
  improvedAnswer?: string;
  trendTopic?: string;
  isIncluded: boolean;
}

export interface PromptPreviewResponse {
  success: boolean;
  data: {
    aiPrompt: string;
    availableExamples: PromptExample[];
    selectedExampleCount: number;
    fieldsToRegenerate: RegenerableField[];
  };
}

export interface RegenerationDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  challengeIndex: number | null;
  challengeData: DailyBuzzDataAdmin | null;
  onRegenerateSuccess: (updatedData: DailyBuzzDataAdmin, message: string) => void;
}

