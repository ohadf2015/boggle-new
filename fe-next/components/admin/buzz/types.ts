// Prompt Template Types (legacy - kept for backward compatibility)
export const TEMPLATE_TYPES = ['riddle', 'image', 'challenge_general', 'social_content'] as const;
export type TemplateType = typeof TEMPLATE_TYPES[number];

export const TEMPLATE_TYPE_LABELS: Record<TemplateType, string> = {
  riddle: 'Riddle Challenges',
  image: 'Image Generation',
  challenge_general: 'General Challenge Generation',
  social_content: 'Social Media Content',
};

export interface TemplatePlaceholder {
  name: string;
  description: string;
}

export interface PromptTemplate {
  id: number;
  template_type: TemplateType;
  language: string | null;
  name: string;
  description: string | null;
  template_content: string;
  placeholders: TemplatePlaceholder[] | null;
  version: number;
  is_active: boolean;
  created_at: string;
  updated_at: string;
}

// ============================================================================
// Prompt Section Types (11 modular sections for AI prompt generation)
