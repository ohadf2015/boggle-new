const EXTRA: Partial<Record<Language, readonly string[]>> = {
  en: EN_EVERYDAY.split(/\s+/).filter(Boolean),
};

/** Common short words for a language, most familiar sources first. */
export function commonStarterWords(language: Language): string[] {
  const helpers = SAME_LENGTH_HELPER_WORDS[language] ?? {};
  const words = [
    ...(EXTRA[language] ?? []),
    ...Object.keys(WORD_FREQUENCY_TIERS[language] ?? {}),
    ...(BONUS_WORD_LISTS[language] ?? []),
    ...Object.values(helpers).flat(),
  ];
  return [...new Set(words.map((w) => w.toUpperCase()))];
}
