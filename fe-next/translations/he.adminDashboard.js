/** Adds each path under `target` without overwriting anything already translated. */
export function mergeAdminDashboardHe(target) {
  for (const [path, text] of Object.entries(adminDashboardHe)) {
    const parts = path.split('.');
    let node = target;
    for (const key of parts.slice(0, -1)) {
      if (node[key] === undefined) node[key] = {};
      node = node[key];
      if (typeof node !== 'object' || node === null) break;
    }
    const leaf = parts[parts.length - 1];
    if (typeof node === 'object' && node !== null && node[leaf] === undefined) node[leaf] = text;
  }
}
